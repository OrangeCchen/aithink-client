export function buildUserPrompt(prdText, screenshotCount, hasAnnotations = false) {
    let shotInfo = '';
    if (screenshotCount === 0 && !hasAnnotations) {
        shotInfo = '\n（本次没有提供设计稿截图，请仅基于 PRD 文字生成；不要使用任何 prd2spec://shot/ 占位符）';
    }
    else if (screenshotCount === 0 && hasAnnotations) {
        shotInfo = '\n（本次通过 MasterGo MCP API 获取了设计稿的结构化数据，见下方"标注信息"部分；没有截图，不要使用 prd2spec://shot/ 占位符）';
    }
    else {
        shotInfo = `\n可用的设计稿截图序号：${Array.from({ length: screenshotCount }, (_, i) => i).join(', ')}（共 ${screenshotCount} 张，按出现顺序对应下方图片附件）。在描述对应页面/区域时使用 \`![区域名](prd2spec://shot/N)\` 引用。`;
    }
    return `请基于下面的 PRD 与设计稿，生成一份面向产品/设计/测试/项目经理阅读的功规。
${shotInfo}

## PRD 原文
${prdText}

## 设计稿
设计稿截图见下方图片附件，请仔细观察：
- 页面整体布局
- 每个区域的组件类型（按钮、输入框、列表、卡片、弹窗等）
- 文字内容、占位符
- 视觉上能看到的不同状态

请按系统提示中要求的结构输出功规。记住：这是给产品/设计/测试/项目经理看的，不要写技术细节。`;
}
